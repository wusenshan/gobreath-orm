// Package gen 为 gobreath-orm 模型提供列名代码生成能力。
//
// 用法：在你的模型文件（如 user.go）上方加一行 go:generate 指令：
//
//	//go:generate go run github.com/wusenshan/gobreath-orm/cmd/ormgen -type User -out user_cols.go
//	package example
//
// 生成器会读取当前目录下的所有 .go 文件（不含测试文件），找到名为 User 的结构体，
// 生成一个 UserColumnSet 类型和一个 UserCols 变量：
//
//	var UserCols = UserColumnSet{
//	    Id:   orm.ColOf[User]("Id"),
//	    Name: orm.ColOf[User]("Name"),
//	    Age:  orm.ColOf[User]("Age"),
//	}
//
// 调用点即可写成：
//
//	orm.NewQuery[User]().Ge(UserCols.Age, 10).Le(UserCols.Age, 20)
package gen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Generate 读取 dir 目录下的 Go 源码，为 types 中列出的结构体生成列名集合文件 outFile。
func Generate(dir string, types []string, outFile string) error {
	if len(types) == 0 {
		return fmt.Errorf("ormgen: 至少指定一个要生成列名集合的结构体类型")
	}
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(info os.FileInfo) bool {
		name := info.Name()
		return !strings.HasSuffix(name, "_test.go") && strings.HasSuffix(name, ".go") && !info.IsDir()
	}, parser.ParseComments)
	if err != nil {
		return fmt.Errorf("ormgen: 解析目录 %s: %w", dir, err)
	}
	if len(pkgs) == 0 {
		return fmt.Errorf("ormgen: 目录 %s 没有可解析的 Go 包", dir)
	}
	// 取目录中的主要包（排除以 _test 结尾的包名，这种包通常只在测试文件里出现）。
	var pkg *ast.Package
	for name, p := range pkgs {
		if strings.HasSuffix(name, "_test") {
			continue
		}
		pkg = p
		break
	}
	if pkg == nil {
		for _, p := range pkgs {
			pkg = p
			break
		}
	}

	type fields struct {
		name   string
		fields []string
	}
	requested := make(map[string][]string, len(types))
	for _, t := range types {
		requested[t] = nil
	}

	for _, file := range pkg.Files {
		for _, decl := range file.Decls {
			ts, ok := decl.(*ast.GenDecl)
			if !ok || ts.Tok != token.TYPE {
				continue
			}
			for _, spec := range ts.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				structName := ts.Name.Name
				if _, want := requested[structName]; !want {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				var list []string
				for _, field := range st.Fields.List {
					if len(field.Names) == 0 {
						continue // 嵌入字段暂不支持
					}
					name := field.Names[0].Name
					if !ast.IsExported(name) {
						continue // 非导出字段无法被外部调用方使用，跳过
					}
					if isIgnoredField(field) {
						continue // db:"-"
					}
					list = append(list, name)
				}
				requested[structName] = list
			}
		}
	}

	var missing []string
	for t, fields := range requested {
		if fields == nil {
			missing = append(missing, t)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("ormgen: 未在目录 %s 中找到结构体: %s", dir, strings.Join(missing, ", "))
	}

	buf := &bytes.Buffer{}
	fmt.Fprintf(buf, "// Code generated by gobreath-orm/cmd/ormgen. DO NOT EDIT.\n\n")
	fmt.Fprintf(buf, "package %s\n\n", pkg.Name)
	fmt.Fprintf(buf, "import orm \"github.com/wusenshan/gobreath-orm\"\n\n")

	orderedTypes := make([]string, 0, len(types))
	for _, t := range types {
		orderedTypes = append(orderedTypes, t)
	}
	sort.Strings(orderedTypes)

	for _, t := range orderedTypes {
		fields := requested[t]
		if len(fields) == 0 {
			continue
		}
		setName := t + "ColumnSet"
		varName := t + "Cols"

		fmt.Fprintf(buf, "// %s 是 %s 的预计算列名集合，字段与 %s 的导出字段一一对应。\n", setName, t, t)
		fmt.Fprintf(buf, "type %s struct {\n", setName)
		for _, f := range fields {
			fmt.Fprintf(buf, "\t%s orm.ColExpr\n", f)
		}
		fmt.Fprintf(buf, "}\n\n")

		fmt.Fprintf(buf, "// %s 提供了 %s 所有导出字段的 ColExpr，可直接用于查询构造器。\n", varName, t)
		fmt.Fprintf(buf, "var %s = %s{\n", varName, setName)
		for _, f := range fields {
			fmt.Fprintf(buf, "\t%s: orm.ColOf[%s](\"%s\"),\n", f, t, f)
		}
		fmt.Fprintf(buf, "}\n\n")
	}

	outPath := filepath.Join(dir, outFile)
	if err := os.MkdirAll(filepath.Dir(outPath), 0755); err != nil {
		return fmt.Errorf("ormgen: 创建输出目录: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("ormgen: 格式化 %s: %w", outPath, err)
	}
	if err := os.WriteFile(outPath, formatted, 0644); err != nil {
		return fmt.Errorf("ormgen: 写入 %s: %w", outPath, err)
	}
	return nil
}

func isIgnoredField(field *ast.Field) bool {
	if field.Tag == nil {
		return false
	}
	tag := strings.Trim(field.Tag.Value, "`")
	for tag != "" {
		name, value, rest, ok := parseStructTag(tag)
		if !ok {
			break
		}
		if name == "db" && (value == "-" || strings.HasPrefix(value, "-,")) {
			return true
		}
		tag = rest
	}
	return false
}

// parseStructTag 是 reflect.StructTag.Lookup 的简化版，只用于判断 db:"-"
func parseStructTag(tag string) (name string, value string, rest string, ok bool) {
	for tag != "" && tag[0] == ' ' {
		tag = tag[1:]
	}
	if tag == "" {
		return "", "", "", false
	}
	skip := 0
	for skip < len(tag) && tag[skip] != ':' {
		skip++
	}
	if skip == 0 || skip+1 >= len(tag) || tag[skip+1] != '"' {
		return "", "", "", false
	}
	name = tag[:skip]
	q := skip + 2
	for q < len(tag) {
		if tag[q] == '\\' && q+1 < len(tag) {
			q += 2
			continue
		}
		if tag[q] == '"' {
			value = tag[skip+2 : q]
			rest = tag[q+1:]
			ok = true
			return
		}
		q++
	}
	return "", "", "", false
}
